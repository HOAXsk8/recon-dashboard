#!/usr/bin/env python3
"""
Purge Redirect False Positives Tool
Safely identifies and purges empty-body (0B) HTTP 301/302/307 catch-all redirect leads
and sensitive_files entries generated by directory brute-forcing on wildcard-redirecting domains.

Guarantees 100% preservation of:
  - HTTP 200 responses with actual payload sizes (True Positives)
  - HTTP 401/403 access control findings
  - Genuine directory trailing-slash normalizations (/dir -> /dir/)
"""

import os
import re
import sys
import argparse
import urllib.parse
import pymongo

def get_mongo_client():
    mongo_host = os.getenv("MONGO_HOST", "localhost")
    mongo_pw = os.getenv("MONGO_ROOT_PASSWORD")
    if mongo_pw:
        encoded_pw = urllib.parse.quote_plus(mongo_pw)
        uri = f"mongodb://admin:{encoded_pw}@{mongo_host}:27017/?authSource=admin"
    else:
        try:
            from app.database import MONGO_URI
            uri = MONGO_URI
        except Exception:
            uri = f"mongodb://{mongo_host}:27017"
    return pymongo.MongoClient(uri)

def run_purge(dry_run=True, target_filter=None):
    client = get_mongo_client()
    db = client["recon_db"]
    leads_col = db["leads"]
    fingerprints_col = db["fingerprints"]
    domains_col = db["domains"]

    mode_str = "DRY RUN (NO CHANGES)" if dry_run else "EXECUTE (LIVE PURGE)"
    print(f"\n============================================================")
    print(f"=== 301/302 REDIRECT FALSE POSITIVE PURGE: {mode_str} ===")
    print(f"============================================================\n")

    # 1. Inspect leads collection
    leads_query = {
        "source": {"$regex": "Directory", "$options": "i"},
        "response_size": 0
    }
    if target_filter:
        leads_query["target"] = target_filter

    candidate_leads = list(leads_col.find(leads_query))
    print(f"[*] Total 0-byte Directory Hunter leads found: {len(candidate_leads)}")

    purged_lead_ids = []
    purged_fingerprints = []
    purged_by_target = {}
    preserved_tps = []

    for lead in candidate_leads:
        lead_id = lead["_id"]
        target = lead.get("target", "unknown")
        title = lead.get("title", "")
        desc = lead.get("description", "")
        details = str(lead.get("details", ""))
        combined_text = f"{desc} {details}"

        # Match HTTP status in description or details: e.g. "(HTTP 301, 0B)" or "status 302"
        status_match = re.search(r"HTTP\s+(30[12378])", combined_text, re.IGNORECASE)
        if not status_match:
            status_match = re.search(r"status\s+(30[12378])", combined_text, re.IGNORECASE)

        if not status_match:
            # Not a 3xx redirect lead; preserve safely
            preserved_tps.append({
                "target": target,
                "title": title,
                "reason": "Non-3xx status or status unknown"
            })
            continue

        http_status = status_match.group(1)

        # Check for directory trailing-slash normalization: e.g. path /admin -> /admin/
        # These are genuine directory discoveries where server normalized the path
        is_trailing_slash_norm = False
        if "location" in details.lower():
            loc_match = re.search(r"location:\s*([^\s,;]+)", details, re.IGNORECASE)
            path_match = re.search(r"(?:discovered:\s*|path\s+)(/[^\s(]+)", combined_text, re.IGNORECASE)
            if loc_match and path_match:
                loc = loc_match.group(1).rstrip("/")
                p = path_match.group(1).rstrip("/")
                if loc.endswith(p):
                    is_trailing_slash_norm = True

        if is_trailing_slash_norm:
            preserved_tps.append({
                "target": target,
                "title": title,
                "reason": f"Directory trailing-slash normalization ({http_status})"
            })
            continue

        # This is a confirmed 0-byte catch-all redirect False Positive
        purged_lead_ids.append(lead_id)
        if lead.get("fingerprint"):
            purged_fingerprints.append(lead["fingerprint"])

        purged_by_target[target] = purged_by_target.get(target, 0) + 1

    print(f"\n[+] Breakdown of 3xx 0-byte False Positive leads to purge ({len(purged_lead_ids)} total):")
    for tgt, count in sorted(purged_by_target.items(), key=lambda x: x[1], reverse=True)[:15]:
        print(f"    - {tgt}: {count} leads")
    if len(purged_by_target) > 15:
        print(f"    ... and {len(purged_by_target) - 15} more targets")

    # 2. Inspect domains collection web_applications for matching sensitive_files
    domains_modified = 0
    sensitive_files_purged = 0

    domain_cursor = domains_col.find({"web_applications": {"$exists": True}})
    for doc in domain_cursor:
        d_id = doc["_id"]
        web_apps = doc.get("web_applications", [])
        modified = False

        new_web_apps = []
        for app in web_apps:
            sens_files = app.get("sensitive_files", [])
            kept_files = []
            for sf in sens_files:
                sf_status = sf.get("status")
                sf_len = sf.get("length", sf.get("size", 0))
                sf_path = sf.get("path", "")

                # If status is 301/302/307 with 0 bytes and not a directory ending with /
                if sf_status in [301, 302, 303, 307, 308] and sf_len == 0 and not sf_path.endswith("/"):
                    sensitive_files_purged += 1
                    modified = True
                else:
                    kept_files.append(sf)

            app["sensitive_files"] = kept_files
            new_web_apps.append(app)

        if modified:
            domains_modified += 1
            if not dry_run:
                domains_col.update_one(
                    {"_id": d_id},
                    {"$set": {"web_applications": new_web_apps}}
                )

    print(f"\n[+] Domain web_applications sensitive_files entries to purge: {sensitive_files_purged}")
    print(f"[+] Total domain documents affected: {domains_modified}")

    # 3. Perform Deletion if not dry-run
    if not dry_run:
        if purged_lead_ids:
            del_result = leads_col.delete_many({"_id": {"$in": purged_lead_ids}})
            print(f"[✓] Deleted {del_result.deleted_count} leads from 'leads' collection.")

        if purged_fingerprints:
            del_fp_result = fingerprints_col.delete_many({"fingerprint": {"$in": purged_fingerprints}})
            print(f"[✓] Deleted {del_fp_result.deleted_count} records from 'fingerprints' collection.")
    else:
        print(f"\n[!] Dry run complete. No records were deleted. Use --execute to apply changes.")

    # 4. Summary & TP Audit
    print(f"\n============================================================")
    print(f"=== PURGE SUMMARY ===")
    print(f"============================================================")
    print(f"  • Total FPs Identified:       {len(purged_lead_ids)}")
    print(f"  • Sensitive Files in Apps:    {sensitive_files_purged}")
    print(f"  • Fingerprint Records:        {len(purged_fingerprints)}")
    print(f"  • Genuine TPs Preserved:      {len(preserved_tps)}")
    print(f"============================================================\n")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Purge 301/302 0-byte catch-all redirect false positives.")
    parser.add_argument("--execute", action="store_true", help="Execute the purge. Defaults to dry-run mode.")
    parser.add_argument("--target", type=str, help="Filter purge to a specific target domain.")
    args = parser.parse_args()

    run_purge(dry_run=not args.execute, target_filter=args.target)
